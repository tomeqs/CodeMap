    /// <summary>A rule by id; a compiler code (code.CS0162, code.TS2367) is described by code.compiler.</summary>
    public static FindingRule? Find(string id) =>
        All.FirstOrDefault(r => r.Id == id)
        ?? (id.StartsWith("code.CS", StringComparison.Ordinal) || id.StartsWith("code.TS", StringComparison.Ordinal) ? All.First(r => r.Id == "code.compiler") : null);
