using System.Diagnostics;
using System.Reflection;
using System.Text;
using CodeMap;
using CodeMap.Analysis;
using CodeMap.Export;
using CodeMap.Model;

return Cli.Run(args);

internal static class Cli
{
    private static readonly string[] AllFormats = { "json", "html", "md", "dgml", "graphml", "cypher" };

    private const string Usage = """
        codemap – maps C# code into a relationship graph and an interactive 3D map.

        Usage:
          codemap <path> [options]                 analyze a .sln/.slnx/.csproj/.cs file or a folder
          codemap export <graph.codemap.json> [options]   convert an existing graph to other formats

        Options:
          -o, --output <dir>       output directory (default: ./codemap-out)
          -f, --format <list>      comma separated: json, html, md, dgml, graphml, cypher, all
                                   (default: json,html,md)
              --name <name>        base name of the output files (default: solution/project name)
              --external           include framework / NuGet types the code depends on
              --no-tests           skip test projects
              --generated          include generated code (*.g.cs, *.Designer.cs, <auto-generated>)
              --no-git             do not read git history (churn / hotspots)
              --git-since <when>   limit git history, e.g. "1 year ago"
              --indent             pretty-print JSON
              --viewer <file>      use a custom viewer template instead of the embedded one
              --open               open the HTML map when done
          -q, --quiet              less output
          -h, --help               show this help
              --version            show version
        """;

    public static int Run(string[] args)
    {
        try
        {
            var options = Parse(args);
            if (options == null) return 0;
            return Execute(options);
        }
        catch (ArgumentException ex)
        {
            Console.Error.WriteLine($"error: {ex.Message}");
            Console.Error.WriteLine("Run 'codemap --help' for usage.");
            return 2;
        }
        catch (FileNotFoundException ex)
        {
            Console.Error.WriteLine($"error: {ex.Message}");
            return 2;
        }
    }

    private sealed class CliOptions
    {
        public bool Export { get; set; }
        public string Input { get; set; } = "";
        public string Output { get; set; } = "codemap-out";
        public HashSet<string> Formats { get; set; } = new() { "json", "html", "md" };
        public string? Name { get; set; }
        public bool Indent { get; set; }
        public bool Open { get; set; }
        public bool Quiet { get; set; }
        public string? Viewer { get; set; }
        public AnalyzerOptions Analyzer { get; } = new();
    }

    private static CliOptions? Parse(string[] args)
    {
        var options = new CliOptions();
        var positional = new List<string>();
        for (var i = 0; i < args.Length; i++)
        {
            var arg = args[i];
            string Next() => i + 1 < args.Length ? args[++i] : throw new ArgumentException($"Missing value for {arg}.");
            switch (arg)
            {
                case "-h" or "--help" or "-?":
                    Console.WriteLine(Usage);
                    return null;
                case "--version":
                    Console.WriteLine(typeof(CodeGraph).Assembly.GetName().Version?.ToString(3));
                    return null;
                case "-o" or "--output":
                    options.Output = Next();
                    break;
                case "-f" or "--format":
                    var formats = Next().Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
                        .Select(f => f.ToLowerInvariant()).ToList();
                    options.Formats = formats.Contains("all") ? AllFormats.ToHashSet() : formats.ToHashSet();
                    var unknown = options.Formats.Except(AllFormats).ToList();
                    if (unknown.Count > 0) throw new ArgumentException($"Unknown format(s): {string.Join(", ", unknown)}.");
                    break;
                case "--name":
                    options.Name = Next();
                    break;
                case "--external":
                    options.Analyzer.IncludeExternal = true;
                    break;
                case "--no-tests":
                    options.Analyzer.IncludeTests = false;
                    break;
                case "--generated":
                    options.Analyzer.IncludeGenerated = true;
                    break;
                case "--no-git":
                    options.Analyzer.Git = false;
                    break;
                case "--git-since":
                    options.Analyzer.GitSince = Next();
                    break;
                case "--indent":
                    options.Indent = true;
                    break;
                case "--viewer":
                    options.Viewer = Next();
                    break;
                case "--open":
                    options.Open = true;
                    break;
                case "-q" or "--quiet":
                    options.Quiet = true;
                    break;
                default:
                    if (arg.StartsWith('-')) throw new ArgumentException($"Unknown option {arg}.");
                    positional.Add(arg);
                    break;
            }
        }

        if (positional.Count > 0 && positional[0] == "export")
        {
            options.Export = true;
            positional.RemoveAt(0);
        }

        if (positional.Count == 0)
        {
            Console.WriteLine(Usage);
            return null;
        }

        if (positional.Count > 1) throw new ArgumentException($"Unexpected argument '{positional[1]}'.");
        options.Input = positional[0];
        return options;
    }

    private static int Execute(CliOptions options)
    {
        void Log(string message)
        {
            if (!options.Quiet) Console.WriteLine(message);
        }

        options.Analyzer.Log = Log;
        var stopwatch = Stopwatch.StartNew();

        CodeGraph graph;
        if (options.Export)
        {
            graph = JsonExporter.Read(options.Input);
            Log($"Loaded {graph.Nodes.Count} nodes, {graph.Edges.Count} edges from {options.Input}");
        }
        else
        {
            graph = CodeMapAnalyzer.Analyze(options.Input, options.Analyzer);
        }

        Directory.CreateDirectory(options.Output);
        var name = Sanitize(options.Name ?? graph.Source.Name);
        var written = new List<string>();

        string PathFor(string extension) => Path.Combine(options.Output, name + extension);

        if (options.Formats.Contains("json") && !options.Export)
        {
            var path = PathFor(".codemap.json");
            using (var stream = File.Create(path)) JsonExporter.Write(graph, stream, options.Indent);
            written.Add(path);
        }

        if (options.Formats.Contains("md"))
        {
            var path = PathFor(".md");
            File.WriteAllText(path, MarkdownReport.Export(graph), Encoding.UTF8);
            written.Add(path);
        }

        if (options.Formats.Contains("dgml"))
        {
            var path = PathFor(".dgml");
            DgmlExporter.Export(graph).Save(path);
            written.Add(path);
        }

        if (options.Formats.Contains("graphml"))
        {
            var path = PathFor(".graphml");
            GraphMLExporter.Export(graph).Save(path);
            written.Add(path);
        }

        if (options.Formats.Contains("cypher"))
        {
            var path = PathFor(".cypher");
            File.WriteAllText(path, CypherExporter.Export(graph), Encoding.UTF8);
            written.Add(path);
        }

        string? htmlPath = null;
        if (options.Formats.Contains("html"))
        {
            var template = LoadViewerTemplate(options.Viewer);
            if (template == null)
            {
                Console.Error.WriteLine("warning: the 3D viewer is not embedded in this build (run `npm run build` in /viewer); skipping HTML output.");
            }
            else
            {
                htmlPath = PathFor(".html");
                File.WriteAllText(htmlPath, HtmlExporter.Export(graph, template), new UTF8Encoding(false));
                written.Add(htmlPath);
            }
        }

        if (!options.Quiet)
        {
            PrintSummary(graph);
            Console.WriteLine();
            foreach (var file in written) Console.WriteLine($"  → {Path.GetFullPath(file)}");
            Console.WriteLine($"Done in {stopwatch.Elapsed.TotalSeconds:0.0}s.");
        }

        if (options.Open && htmlPath != null) OpenInBrowser(Path.GetFullPath(htmlPath));
        return 0;
    }

    private static void PrintSummary(CodeGraph graph)
    {
        var byId = graph.Nodes.ToDictionary(n => n.Id);
        Console.WriteLine();
        Console.WriteLine($"{graph.Stats.GetValueOrDefault("projects")} projects · {graph.Stats.GetValueOrDefault("namespaces")} namespaces · " +
                          $"{graph.Stats.GetValueOrDefault("types")} types · {graph.Stats.GetValueOrDefault("members")} members · " +
                          $"{graph.Stats.GetValueOrDefault("edges")} relationships · {graph.Stats.GetValueOrDefault("lines")} lines");

        var cycles = graph.Analysis.Cycles;
        if (cycles.Count > 0)
        {
            Console.WriteLine($"Cycles: {cycles.Count(c => c.Level == "type")} between types, {cycles.Count(c => c.Level == "namespace")} between namespaces");
        }

        if (graph.Analysis.Hotspots.Count > 0)
        {
            Console.WriteLine("Hotspots: " + string.Join(", ", graph.Analysis.Hotspots.Take(5).Select(h => byId[h.Id].Name)));
        }
        else if (graph.Analysis.MostComplex.Count > 0)
        {
            Console.WriteLine("Most complex: " + string.Join(", ", graph.Analysis.MostComplex.Take(5).Select(h => byId[h.Id].Name)));
        }

        if (graph.Analysis.UnusedCandidates.Count > 0) Console.WriteLine($"Possibly unused: {graph.Analysis.UnusedCandidates.Count} symbols");
        if (graph.Analysis.Warnings.Count > 0) Console.WriteLine($"Warnings: {graph.Analysis.Warnings.Count} (see the .md report)");
    }

    private static string? LoadViewerTemplate(string? customPath)
    {
        if (customPath != null) return File.ReadAllText(customPath);
        using var stream = Assembly.GetExecutingAssembly().GetManifestResourceStream("CodeMap.viewer.html");
        if (stream == null) return null;
        using var reader = new StreamReader(stream, Encoding.UTF8);
        return reader.ReadToEnd();
    }

    private static string Sanitize(string name)
    {
        var invalid = Path.GetInvalidFileNameChars();
        var clean = new string(name.Select(c => invalid.Contains(c) ? '_' : c).ToArray());
        return string.IsNullOrWhiteSpace(clean) ? "codemap" : clean;
    }

    private static void OpenInBrowser(string path)
    {
        try
        {
            if (OperatingSystem.IsWindows()) Process.Start(new ProcessStartInfo(path) { UseShellExecute = true });
            else if (OperatingSystem.IsMacOS()) Process.Start("open", path);
            else Process.Start("xdg-open", path);
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"Could not open the browser: {ex.Message}");
        }
    }
}
