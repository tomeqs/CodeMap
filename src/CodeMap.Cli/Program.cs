internal static class Cli
{
    private static readonly string[] AllFormats = { "json", "html", "md", "dgml", "graphml", "cypher" };

    private const string Usage = """
        codemap – maps C# code (and TypeScript / JavaScript, with Node.js) into a relationship graph and an interactive 3D map.

        Usage:
          codemap                                  open the CodeMap app in your browser (pick or clone a project there)
          codemap ui [path] [--watch]              same, and start analyzing <path> right away
          codemap <path> [options]                 analyze a .sln/.slnx/.slnf/.csproj/.cs file, a package.json/tsconfig.json/.ts file
                                                   or a folder (every language found in it, merged into one map) into files
          codemap export <graph.codemap.json> [options]   convert an existing graph to other formats
          codemap mcp [path] [mcp options]         run as an MCP server (stdio) for AI agents: the map, findings, call flows,
                                                   diagrams; e.g. claude mcp add codemap -- codemap mcp

        Options:
          -o, --output <dir>       output directory (default: ./codemap-out)
          -f, --format <list>      comma separated: json, html, md, dgml, graphml, cypher, all
                                   (default: json,html,md)
              --name <name>        base name of the output files (default: solution/project/package name)
              --external           include framework / NuGet types the code depends on
              --no-tests           skip test projects
              --generated          include generated code (*.g.cs, *.Designer.cs, <auto-generated>)
              --types-only         drop member nodes, keep their relationships rolled up to types
                                   (much smaller output for very large solutions)
              --lang <list>        only these languages, e.g. csharp or typescript (default: all that are found)
              --plugins <dir>      also look for language plugins in <dir>
              --checks             also check the code inside function bodies (swallowed exceptions, sync over async,
                                   floating promises, unreachable code, selected compiler warnings); in the .md report
              --no-git             do not read git history (churn / hotspots)
              --git-since <when>   limit git history, e.g. "1 year ago"
              --indent             pretty-print JSON
              --viewer <file>      use a custom viewer template instead of the embedded one
              --open               open the HTML map when done

        MCP options (codemap mcp):
              --root <dir>         folder that relative paths start from (default: the client's root, else the current one)
              --no-watch           do not watch the sources (answers then never say the analysis is stale)
              --max-output <n>     the most characters of one tool answer (default 30000; longer lists are cut)
              --no-checks          do not check function bodies (on by default for agents)
              --browser <path>     Chrome, Edge or Chromium for render_map (default: CODEMAP_BROWSER, else the installed one)
              (--lang, --plugins, --no-git, --git-since, --no-tests, --generated, --external work as for analysis)

        App options (codemap / codemap ui):
              --port <n>           preferred port (default 5180; a free one is used if taken)
              --no-open            do not open the browser
              --watch              re-analyze automatically when the sources change

          -q, --quiet              less output
          -h, --help               show this help
              --version            show version
        """;

    public static int Run(string[] args)
    {
        try
        {
            if (args.Length > 0 && args[0] == "mcp") return McpCommand.Run(args[1..]);
            var options = Parse(args);
            if (options == null) return 0;
            return options.Ui ? RunUiAsync(options).GetAwaiter().GetResult() : Execute(options);
        }
        catch (ArgumentException ex)
        {
            Console.Error.WriteLine($"error: {ex.Message}");
            Console.Error.WriteLine("Run 'codemap --help' for usage.");
            return 2;
        }
        catch (FileNotFoundException ex)
        {
            Console.Error.WriteLine($"error: {ex.Message}");
            return 2;
        }
        catch (Exception ex) when (ex is InvalidOperationException or InvalidDataException or TimeoutException)
        {
            Console.Error.WriteLine($"error: {ex.Message}");
            return 1;
        }
    }

    private sealed class CliOptions
    {
        public bool Export { get; set; }
        public string Input { get; set; } = "";
        public string Output { get; set; } = "codemap-out";
        public HashSet<string> Formats { get; set; } = new() { "json", "html", "md" };
        public string? Name { get; set; }
        public bool Indent { get; set; }
        public bool TypesOnly { get; set; }
        public bool Open { get; set; }
        public bool Quiet { get; set; }
        public string? Viewer { get; set; }
        public bool Ui { get; set; }
        public int Port { get; set; } = 5180;
        public bool NoOpen { get; set; }
        public bool Watch { get; set; }
        public List<string>? Languages { get; set; }
        public string? Plugins { get; set; }
        public AnalyzerOptions Analyzer { get; } = new();

        /// <summary>The languages to use: C# and the plugins found (also in --plugins), limited by --lang.</summary>
        public LanguageRegistry Registry()
        {
            var registry = Plugins != null ? LanguageRegistry.WithPlugins(PluginCatalog.DefaultFolders().Prepend(Plugins)) : LanguageRegistry.Default;
            return Languages != null ? registry.Only(Languages) : registry;
        }
    }

    private static CliOptions? Parse(string[] args)
    {
        var options = new CliOptions();
        var positional = new List<string>();
        var showVersion = false;
        for (var i = 0; i < args.Length; i++)
        {
            var arg = args[i];
            string Next() => i + 1 < args.Length ? args[++i] : throw new ArgumentException($"Missing value for {arg}.");
            switch (arg)
            {
                case "-h" or "--help" or "-?":
                    Console.WriteLine(Usage);
                    return null;
                case "--version":
                    showVersion = true;
                    break;
                case "--lang":
                    options.Languages = Next().Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries).ToList();
                    break;
                case "--plugins":
                    options.Plugins = Path.GetFullPath(Next());
                    break;
                case "-o" or "--output":
                    options.Output = Next();
                    break;
                case "-f" or "--format":
                    var formats = Next().Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
                        .Select(f => f.ToLowerInvariant()).ToList();
                    options.Formats = formats.Contains("all") ? AllFormats.ToHashSet() : formats.ToHashSet();
                    var unknown = options.Formats.Except(AllFormats).ToList();
                    if (unknown.Count > 0) throw new ArgumentException($"Unknown format(s): {string.Join(", ", unknown)}.");
                    break;
                case "--name":
                    options.Name = Next();
                    break;
                case "--external":
                    options.Analyzer.IncludeExternal = true;
                    break;
                case "--no-tests":
                    options.Analyzer.IncludeTests = false;
                    break;
                case "--generated":
                    options.Analyzer.IncludeGenerated = true;
                    break;
                case "--no-git":
                    options.Analyzer.Git = false;
                    break;
                case "--checks":
                    options.Analyzer.CodeChecks = true;
                    break;
                case "--git-since":
                    options.Analyzer.GitSince = Next();
                    break;
                case "--indent":
                    options.Indent = true;
                    break;
                case "--types-only":
                    options.TypesOnly = true;
                    break;
                case "--viewer":
                    options.Viewer = Next();
                    break;
                case "--open":
                    options.Open = true;
                    break;
                case "-q" or "--quiet":
                    options.Quiet = true;
                    break;
                case "--port":
                    options.Port = int.TryParse(Next(), out var port) && port is >= 0 and <= 65535 ? port : throw new ArgumentException("--port expects a number between 0 and 65535.");
                    break;
                case "--no-open":
                    options.NoOpen = true;
                    break;
                case "--watch":
                    options.Watch = true;
                    break;
                default:
                    if (arg.StartsWith('-')) throw new ArgumentException($"Unknown option {arg}.");
                    positional.Add(arg);
                    break;
            }
        }

        if (showVersion)
        {
            PrintVersion(options);
            return null;
        }

        if (positional.Count > 0 && positional[0] == "export")
        {
            options.Export = true;
            positional.RemoveAt(0);
        }

        if (positional.Count > 0 && positional[0] == "ui")
        {
            options.Ui = true;
            positional.RemoveAt(0);
        }

        // No arguments at all: start the app – the friendliest way in.
        if (positional.Count == 0 && !options.Export)
        {
            options.Ui = true;
            return options;
        }

        if (positional.Count == 0)
        {
            Console.WriteLine(Usage);
            return null;
        }

        if (positional.Count > 1) throw new ArgumentException($"Unexpected argument '{positional[1]}'.");
        options.Input = positional[0];
        return options;
    }

    private static void PrintVersion(CliOptions options)
    {
        Console.WriteLine(typeof(CodeGraph).Assembly.GetName().Version?.ToString(3));
        Console.WriteLine($"Framework references: {FrameworkLocator.Describe()}");
        var registry = options.Registry();
        Console.WriteLine("Languages:");
        foreach (var language in registry.Languages)
        {
            if (language is not ExternalProcessAnalyzer plugin)
            {
                Console.WriteLine($"  {language.Info.Name} ({language.Info.Id}): built in");
                continue;
            }

            var where = $"plugin {plugin.Manifest.Version} in {plugin.Manifest.Directory}";
            if (plugin.Manifest.Runtime is not { } runtime)
            {
                Console.WriteLine($"  {language.Info.Name} ({language.Info.Id}): {where}");
                continue;
            }

            var (found, problem) = RuntimeLocator.Find(runtime);
            Console.WriteLine(found != null
                ? $"  {language.Info.Name} ({language.Info.Id}): {where}, {runtime.Name} {found.Version} at {found.Path}"
                : $"  {language.Info.Name} ({language.Info.Id}): {where} – not available: {problem}");
        }

        foreach (var problem in registry.Problems) Console.WriteLine($"  ignored: {problem}");
    }

    private static int Execute(CliOptions options)
    {
        void Log(string message)
        {
            if (!options.Quiet) Console.WriteLine(message);
        }

        options.Analyzer.Log = Log;
        var stopwatch = Stopwatch.StartNew();

        CodeGraph graph;
        if (options.Export)
        {
            graph = JsonExporter.Read(options.Input);
            Log($"Loaded {graph.Nodes.Count} nodes, {graph.Edges.Count} edges from {options.Input}");
        }
        else
        {
            graph = CodeMapAnalyzer.Analyze(options.Input, options.Registry(), options.Analyzer);
        }

        if (options.TypesOnly) GraphView.CollapseMembers(graph);

        Directory.CreateDirectory(options.Output);
        var name = Sanitize(options.Name ?? graph.Source.Name);
        var written = new List<string>();

        string PathFor(string extension) => Path.Combine(options.Output, name + extension);

        // Re-exporting a graph only rewrites the JSON when it was transformed (--types-only), never over its input.
        if (options.Formats.Contains("json") && (!options.Export || options.TypesOnly))
        {
            var path = PathFor(".codemap.json");
            if (options.Export && Path.GetFullPath(path) == Path.GetFullPath(options.Input)) path = PathFor(".types.codemap.json");
            using (var stream = File.Create(path)) JsonExporter.Write(graph, stream, options.Indent);
            written.Add(path);
        }

        if (options.Formats.Contains("md"))
        {
            var path = PathFor(".md");
            File.WriteAllText(path, MarkdownReport.Export(graph), Encoding.UTF8);
            written.Add(path);
        }

        if (options.Formats.Contains("dgml"))
        {
            var path = PathFor(".dgml");
            DgmlExporter.Export(graph).Save(path);
            written.Add(path);
        }

        if (options.Formats.Contains("graphml"))
        {
            var path = PathFor(".graphml");
            GraphMLExporter.Export(graph).Save(path);
            written.Add(path);
        }

        if (options.Formats.Contains("cypher"))
        {
            var path = PathFor(".cypher");
            File.WriteAllText(path, CypherExporter.Export(graph), Encoding.UTF8);
            written.Add(path);
        }

        string? htmlPath = null;
        if (options.Formats.Contains("html"))
        {
            var template = LoadViewerTemplate(options.Viewer);
            if (template == null)
            {
                Console.Error.WriteLine("warning: the 3D viewer is not embedded in this build (run `npm run build` in /viewer); skipping HTML output.");
            }
            else
            {
                htmlPath = PathFor(".html");
                File.WriteAllText(htmlPath, HtmlExporter.Export(graph, template), new UTF8Encoding(false));
                written.Add(htmlPath);
            }
        }

        if (!options.Quiet)
        {
            PrintSummary(graph);
            Console.WriteLine();
            foreach (var file in written) Console.WriteLine($"  → {Path.GetFullPath(file)}");
            Console.WriteLine($"Done in {stopwatch.Elapsed.TotalSeconds:0.0}s.");
        }

        if (options.Open && htmlPath != null) OpenInBrowser(Path.GetFullPath(htmlPath));
        return 0;
    }

    private static async Task<int> RunUiAsync(CliOptions options)
    {
        var template = LoadViewerTemplate(options.Viewer);
        if (template == null)
        {
            Console.Error.WriteLine("error: the viewer is not embedded in this build (run `npm run build` in /viewer).");
            return 1;
        }

        var settings = new AnalysisSettings
        {
            Tests = options.Analyzer.IncludeTests,
            External = options.Analyzer.IncludeExternal,
            Git = options.Analyzer.Git,
            TypesOnly = options.TypesOnly,
            Watch = options.Watch,
        };

        await using var server = await UiServer.StartAsync(new UiServerOptions
        {
            ViewerHtml = template,
            Port = options.Port,
            InitialPath = string.IsNullOrEmpty(options.Input) ? null : Path.GetFullPath(options.Input),
            InitialSettings = settings,
            Log = options.Quiet ? null : message => Console.WriteLine($"  {message}"),
        });

        Console.WriteLine($"CodeMap is running at {server.Url}");
        // For `npm run dev` in /viewer: the dev server proxies /api and needs the session token.
        if (Environment.GetEnvironmentVariable("CODEMAP_DEV") == "1") Console.WriteLine($"Dev viewer: http://localhost:5173/?token={server.Token}");
        Console.WriteLine("Pick a solution, package or folder in the browser. Press Ctrl+C to stop.");
        if (!options.NoOpen) OpenInBrowser(server.Url);

        // The host's console lifetime handles Ctrl+C and SIGTERM.
        await server.WaitForShutdownAsync();
        Console.WriteLine("Stopping.");
        return 0;
    }

    private static void PrintSummary(CodeGraph graph)
    {
        var byId = graph.Nodes.ToDictionary(n => n.Id);
        Console.WriteLine();
        Console.WriteLine($"{graph.Stats.GetValueOrDefault("projects")} projects · {graph.Stats.GetValueOrDefault("namespaces")} namespaces · " +
                          $"{graph.Stats.GetValueOrDefault("types")} types · {graph.Stats.GetValueOrDefault("members")} members · " +
                          $"{graph.Stats.GetValueOrDefault("edges")} relationships · {graph.Stats.GetValueOrDefault("lines")} lines");

        var cycles = graph.Analysis.Cycles;
        if (cycles.Count > 0)
        {
            Console.WriteLine($"Cycles: {cycles.Count(c => c.Level == "type")} between types, {cycles.Count(c => c.Level == "namespace")} between namespaces");
        }

        if (graph.Analysis.Hotspots.Count > 0)
        {
            Console.WriteLine("Hotspots: " + string.Join(", ", graph.Analysis.Hotspots.Take(5).Select(h => byId[h.Id].Name)));
        }
        else if (graph.Analysis.MostComplex.Count > 0)
        {
            Console.WriteLine("Most complex: " + string.Join(", ", graph.Analysis.MostComplex.Take(5).Select(h => byId[h.Id].Name)));
        }

        if (graph.Analysis.Layers.FirstOrDefault(l => l.Level == "namespace") is { } layers)
        {
            Console.WriteLine($"Layers: {layers.Layers.Count} namespace layers, {layers.Upward.Count} upward dependencies");
        }

        if (graph.Analysis.Di is { } di)
        {
            var errors = di.Issues.Count(i => i.Severity == "error");
            var notes = di.Issues.Count(i => i.Severity == "info");
            var warnings = di.Issues.Count - errors - notes;
            Console.WriteLine($"DI: {di.Registrations.Count} registrations, {errors} error(s), {warnings} warning(s)" + (notes > 0 ? $", {notes} note(s)" : ""));
        }

        var hiddenCoupling = graph.Analysis.ChangeCoupling.Count(c => c.Hidden);
        if (hiddenCoupling > 0) Console.WriteLine($"Hidden change coupling: {hiddenCoupling} pairs of types change together without a code dependency");
        if (graph.Analysis.UnusedCandidates.Count > 0) Console.WriteLine($"Possibly unused: {graph.Analysis.UnusedCandidates.Count} symbols");
        if (graph.Analysis.Warnings.Count > 0) Console.WriteLine($"Warnings: {graph.Analysis.Warnings.Count} (see the .md report)");
    }

    private static string? LoadViewerTemplate(string? customPath)
    {
        if (customPath != null) return File.ReadAllText(customPath);
        using var stream = Assembly.GetExecutingAssembly().GetManifestResourceStream("CodeMap.viewer.html");
        if (stream == null) return null;
        using var reader = new StreamReader(stream, Encoding.UTF8);
        return reader.ReadToEnd();
    }

    private static string Sanitize(string name)
    {
        var invalid = Path.GetInvalidFileNameChars();
        var clean = new string(name.Select(c => invalid.Contains(c) ? '_' : c).ToArray());
        return string.IsNullOrWhiteSpace(clean) ? "codemap" : clean;
    }

    private static void OpenInBrowser(string path)
    {
        try
        {
            if (OperatingSystem.IsWindows()) Process.Start(new ProcessStartInfo(path) { UseShellExecute = true });
            else if (OperatingSystem.IsMacOS()) Process.Start("open", path);
            else Process.Start(new ProcessStartInfo("xdg-open", path) { RedirectStandardError = true, RedirectStandardOutput = true });
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"Could not open the browser: {ex.Message}");
        }
    }
}
