import { existsSync, readFileSync, readdirSync, statSync } from 'node:fs';
import { homedir } from 'node:os';
import { basename, dirname, extname, join, relative, resolve, sep } from 'node:path';

const manifest = JSON.parse(readFileSync(new URL('../codemap-plugin.json', import.meta.url), 'utf8'));

export const SOURCE_EXTENSIONS = new Set(['.c', '.cc', '.cpp', '.cxx', '.c++', '.cp']);
export const HEADER_EXTENSIONS = new Set(['.h', '.hh', '.hpp', '.hxx', '.h++', '.ipp', '.inl', '.tpp', '.ixx']);
const CPP_HEADERS = new Set(['.hh', '.hpp', '.hxx', '.h++', '.ipp', '.inl', '.tpp', '.ixx']);

const IGNORED = manifest.detect.ignoreDirs.filter((d) => !d.includes('*'));
const IGNORED_PATTERNS = manifest.detect.ignoreDirs.filter((d) => d.includes('*')).map((d) => new RegExp('^' + d.replace(/[.+^${}()|[\]\\]/g, '\\$&').replace(/\*/g, '.*') + '$', 'i'));
const IGNORED_MARKERS = manifest.detect.ignoreMarkers ?? [];
const EXCLUDED_FILES = manifest.detect.excludeFiles.map((p) => new RegExp('^' + p.replace(/[.+^${}()|[\]\\]/g, '\\$&').replace(/\*/g, '.*') + '$', 'i'));
/** Copies of other projects' code, kept beside the project's own: their headers are a library's. */
const VENDORED = new Set(['third_party', 'third-party', 'thirdparty', '3rdparty', '3rd_party', 'external', 'externals', 'extern', 'vendor', 'vendored', 'deps']);
/** Folders of build output that hold no code of the project. */
const OUTPUT = new Set(['x64', 'x86', 'Debug', 'Release', 'RelWithDebInfo', 'MinSizeRel', 'out', 'ipch']);

/** The build files a folder can hold, with the project kind each one makes. */
const FOLDER_MARKERS = new Set(['meson.build', 'Makefile', 'GNUmakefile', 'makefile', 'BUILD', 'BUILD.bazel', 'MODULE.bazel', 'WORKSPACE', 'configure.ac', 'premake5.lua', 'xmake.lua', 'vcpkg.json', 'conanfile.txt', 'conanfile.py']);

export const toPosix = (path) => path.split(sep).join('/');

export function isSourceFile(path) {
  return SOURCE_EXTENSIONS.has(extname(path).toLowerCase());
}

export function isHeaderFile(path) {
  return HEADER_EXTENSIONS.has(extname(path).toLowerCase());
}

/** The grammar a file is read with before its includes are known: .c is C, sources and C++ headers C++, .h open. */
export function grammarOf(path) {
  const ext = extname(path).toLowerCase();
  if (ext === '.c') return 'c';
  if (SOURCE_EXTENSIONS.has(ext) || CPP_HEADERS.has(ext)) return 'cpp';
  return null;
}

/** Test code by folder or name: test/, tests/, *_test.cpp, *_unittest.cc, test_*.c, *Test.cpp, *Tests.cpp. */
export function isTestFile(path) {
  return /(^|\/)(tests?|unittests?|unit_tests?|testing|gtest|spec|specs)\//i.test(path)
    || /(^|\/)(test_[^/]*|[^/]*[_-](test|tests|unittest|spec)|[^/]*[a-z0-9](Test|Tests|Spec))\.(c|cc|cpp|cxx|c\+\+|h|hh|hpp)$/.test(path);
}

/** Files a tool wrote: by name (moc_, qrc_, ui_*.h, *.generated.h, *.pb.h) or a mark at the top. */
export function isGenerated(path, text) {
  const name = basename(path);
  if (EXCLUDED_FILES.some((re) => re.test(name))) return true;
  if (/^ui_.*\.h$/.test(name) || /\.(generated|gen)\.(h|hpp|cpp)$/i.test(name) || /\.pb\.(h|cc|c)$/.test(name) || /\.grpc\.pb\./.test(name)) return true;
  const head = text.slice(0, 1024);
  return /@generated|<auto-generated|automatically generated by|generated by (the )?(moc|uic|rcc|protoc|flex|bison|SWIG)|DO NOT EDIT/i.test(head);
}

/**
 * The files to analyze and the build files around them. The folder given may be inside a project (src/ of a
 * CMake project): its build files are above it, and are read from there so the ids do not depend on the folder.
 */
export function discover(target) {
  const full = resolve(target);
  const isFile = statSync(full).isFile();
  const scanDir = isFile ? dirname(full) : full;
  const files = [];
  const markers = { cmake: [], vcxproj: [], buildCs: [], uproject: [], folder: [], compileCommands: [] };
  let only = null;
  let solution = null;
  if (isFile) {
    if (/\.(sln|slnx)$/i.test(full)) solution = full;
    else if (/\.vcxproj$/i.test(full)) markers.vcxproj.push(full);
    else if (basename(full) === 'CMakeLists.txt') walk(scanDir, files, markers, scanDir);
    else if (isSourceFile(full) || isHeaderFile(full)) only = full;
    if (solution || markers.vcxproj.length) walk(scanDir, files, markers, scanDir);
  } else {
    walk(scanDir, files, markers, scanDir);
  }

  // Build files above the folder (it is inside a project).
  // CMake folders above, nearest first: the topmost is read (its add_subdirectory chain reaches this folder).
  const above = { cmake: [], vcxproj: [], buildCs: [], folder: null };
  const stop = repositoryBoundary(scanDir);
  let dir = scanDir;
  for (let parent = dirname(dir); parent !== dir && dir !== stop; dir = parent, parent = dirname(dir)) {
    if (parent === homedir()) break;
    let names;
    try {
      names = readdirSync(parent);
    } catch {
      break;
    }

    if (names.includes('CMakeLists.txt')) above.cmake.push(parent);

    if (!above.vcxproj.length && !markers.vcxproj.length) above.vcxproj = names.filter((n) => /\.vcxproj$/i.test(n)).map((n) => join(parent, n));
    if (!above.buildCs.length && !markers.buildCs.length) above.buildCs = names.filter((n) => /\.Build\.cs$/i.test(n)).map((n) => join(parent, n));
    if (!above.folder && names.some((n) => FOLDER_MARKERS.has(n))) above.folder = parent;
    if (names.includes('.git')) break;
  }

  return { scanDir, files: only ? [only] : files, only, solution, markers, above, repository: stop };
}

function walk(dir, files, markers, scanDir, depth = 0) {
  let entries;
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    return;
  }

  const names = entries.map((e) => e.name);
  if (dir !== scanDir && (names.includes('CMakeCache.txt') || IGNORED_MARKERS.some((m) => names.includes(m)))) return;
  for (const entry of entries) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (skipsFolder(entry.name)) continue;
      if (depth < 64) walk(path, files, markers, scanDir, depth + 1);
    } else if (entry.isFile() || entry.isSymbolicLink()) {
      const name = entry.name;
      if (name === 'CMakeLists.txt') markers.cmake.push(path);
      else if (/\.vcxproj$/i.test(name)) markers.vcxproj.push(path);
      else if (/\.Build\.cs$/i.test(name)) markers.buildCs.push(path);
      else if (/\.(uproject|uplugin)$/i.test(name)) markers.uproject.push(path);
      else if (name === 'compile_commands.json') markers.compileCommands.push(path);
      else if (FOLDER_MARKERS.has(name)) markers.folder.push(path);
      else if ((isSourceFile(name) || isHeaderFile(name)) && (entry.isFile() || isFileTarget(path))) files.push(path);
    }
  }
}

export function skipsFolder(name) {
  return name.startsWith('.') || IGNORED.includes(name) || IGNORED_PATTERNS.some((re) => re.test(name)) || VENDORED.has(name.toLowerCase()) || OUTPUT.has(name);
}

function isFileTarget(path) {
  try {
    return statSync(path).isFile();
  } catch {
    return false;
  }
}

/** Where the search for build files above a folder stops: the repository root, or the folder itself without one. */
function repositoryBoundary(dir) {
  for (let d = dir, parent = dirname(d); ; d = parent, parent = dirname(d)) {
    if (existsSync(join(d, '.git'))) return d;
    if (parent === d || parent === homedir()) return null;
  }
}

/** Line count of a text, as editors count them. */
export function lineCount(text) {
  let count = 1;
  for (let i = 0; i < text.length; i++) if (text.charCodeAt(i) === 10) count++;
  return text.endsWith('\n') ? count - 1 : count;
}

export function readText(path) {
  try {
    const text = readFileSync(path, 'utf8');
    // A byte order mark is not code: behind it, a first-line #include or #define does not start its line.
    return text.charCodeAt(0) === 0xfeff ? text.slice(1) : text;
  } catch {
    return null;
  }
}

/** The includes of a file, read from its text: `#include "x.h"` (quoted: local first) and `<x.h>`. */
export function includesOf(text) {
  const out = [];
  if (!text.includes('include')) return out;
  const re = /^[ \t]*#[ \t]*(?:include|import|include_next)[ \t]*([<"])([^>"\n]+)[>"]/gm;
  let m;
  while ((m = re.exec(text))) out.push({ path: m[2].trim(), quoted: m[1] === '"' });
  return out;
}

export { relative };
