import { existsSync, readFileSync, readdirSync, statSync } from 'node:fs';
import { homedir } from 'node:os';
import { basename, dirname, extname, join, relative, resolve, sep } from 'node:path';

const manifest = JSON.parse(readFileSync(new URL('../codemap-plugin.json', import.meta.url), 'utf8'));
const SOURCE_EXTENSIONS = new Set(manifest.detect.sources);
const TS_EXTENSIONS = new Set(['.ts', '.tsx', '.mts', '.cts']);
const IGNORED_DIRS = new Set(manifest.detect.ignoreDirs);
const CONFIGS = ['tsconfig.json', 'jsconfig.json'];

/** Code files the analysis reads: not declaration files (.d.ts), not minified bundles. */
export function isSource(file) {
  const name = basename(file);
  return SOURCE_EXTENSIONS.has(extname(name)) && !/\.d\.[cm]?ts$/.test(name) && !/\.min\.[cm]?js$/.test(name);
}

/** Test files by name or folder: *.spec.ts, *.test.js, __tests__/, e2e/. */
export function isTestFile(path) {
  return /(^|\/)(__tests__|__mocks__|e2e|cypress)\//.test(path) || /\.(spec|test|e2e-spec)\.[cm]?[jt]sx?$/.test(path);
}

/** Files that a tool wrote: *.generated.ts, or marked @generated / <auto-generated> at the top. */
export function isGenerated(file, text) {
  if (/\.(generated|g)\.[cm]?[jt]sx?$/.test(file)) return true;
  const head = text.slice(0, 1024);
  return /@generated|<auto-generated|autogenerated by/i.test(head);
}

export const toPosix = (path) => path.split(sep).join('/');

/**
 * The packages to analyze and their files. A package is a folder with a package.json; every file belongs to the
 * nearest one above it. Folders of a monorepo that only declare workspaces end up with no files and are left
 * out. TypeScript with no package.json around becomes one package named after the folder; loose JavaScript
 * without one (copied libraries) is left alone.
 */
export function discover(target, root, { includeTests = true } = {}) {
  const full = resolve(target);
  const isFile = statSync(full).isFile();
  const scanDir = isFile ? dirname(full) : full;
  const onlyFile = isFile && isSource(full) ? full : null;

  const files = [];
  const packageDirs = new Set();
  const configDirs = new Set();
  const links = new Set();
  if (onlyFile) files.push(onlyFile);
  else walk(scanDir, files, packageDirs, configDirs, links);

  // The folder or file given may be inside a package (src/ of an app, one file): its package.json is above,
  // also above the analysis root (CodeMap passes the folder given as the root). The search stops at the
  // first package.json, at the repository root (.git), and before the home folder (a stray ~/package.json
  // is not the package of everything under it).
  const home = homedir();
  for (let dir = scanDir; dir !== home; dir = dirname(dir)) {
    if (CONFIGS.some((c) => existsSync(join(dir, c)))) configDirs.add(dir);
    if (packageDirs.has(dir) || existsSync(join(dir, 'package.json'))) {
      packageDirs.add(dir);
      break;
    }

    if (existsSync(join(dir, '.git')) || dir === dirname(dir)) break;
  }

  const ownerOf = (file) => {
    for (let dir = dirname(file); ; dir = dirname(dir)) {
      if (packageDirs.has(dir)) return dir;
      if (dir === dirname(dir)) return null;
    }
  };
  const inConfig = (file) => [...configDirs].some((dir) => file.startsWith(dir + sep) || dirname(file) === dir);

  const byDir = new Map();
  let skippedTests = 0;
  for (const file of files) {
    let dir = ownerOf(file);
    if (!dir) {
      if (!TS_EXTENSIONS.has(extname(file)) && !inConfig(file)) continue; // stray JavaScript
      dir = scanDir;
    }

    if (!includeTests && isTestFile(toPosix(relative(dir, file)))) {
      skippedTests++;
      continue;
    }

    if (!byDir.has(dir)) byDir.set(dir, []);
    byDir.get(dir).push(file);
  }

  const packages = new Map(); // workspace packages by name, for imports between them
  for (const dir of packageDirs) {
    const json = readJson(join(dir, 'package.json'));
    if (json?.name) packages.set(json.name, { dir, json });
  }

  const names = new Set();
  const projects = [...byDir.entries()]
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([dir, list]) => {
      const json = packageDirs.has(dir) ? readJson(join(dir, 'package.json')) ?? {} : {};
      let name = json.name || basename(dir);
      for (let i = 2; names.has(name); i++) name = `${json.name || basename(dir)}~${i}`;
      names.add(name);
      return { dir, name, json, hasPackageJson: packageDirs.has(dir), files: list.sort() };
    });

  return { projects, packages, skippedTests, links };
}

/** Collects the files under a folder; a symbolic link to a source file is a file (by the link's path), not followed into folders. */
function walk(dir, files, packageDirs, configDirs, links) {
  let entries;
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    return;
  }

  for (const entry of entries) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (IGNORED_DIRS.has(entry.name) || entry.name.startsWith('.')) continue;
      walk(path, files, packageDirs, configDirs, links);
    } else if (entry.isFile()) {
      if (entry.name === 'package.json') packageDirs.add(dir);
      else if (CONFIGS.includes(entry.name)) configDirs.add(dir);
      else if (isSource(path)) files.push(path);
    } else if (entry.isSymbolicLink() && isSource(path) && isFileTarget(path)) {
      files.push(path);
      links.add(toPosix(path));
    }
  }
}

function isFileTarget(path) {
  try {
    return statSync(path).isFile();
  } catch {
    return false; // a broken link
  }
}

export function readJson(path) {
  try {
    return JSON.parse(readFileSync(path, 'utf8'));
  } catch {
    return null;
  }
}

/** Line count of a text, as editors count them. */
export function lineCount(text) {
  let count = 1;
  for (let i = 0; i < text.length; i++) if (text.charCodeAt(i) === 10) count++;
  return text.endsWith('\n') ? count - 1 : count;
}

export { statSync };
