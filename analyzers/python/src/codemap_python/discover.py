"""The projects and modules to analyze.

A project is a folder with a project file (pyproject.toml, setup.py, setup.cfg, Pipfile, requirements.txt); every
file belongs to the nearest one above it. Files with none above them form one project named after the analyzed
folder (a folder of scripts). A folder inside a project is analyzed as part of it: the project file above it gives
the ids and the modules imports reach, but only the files inside the folder are on the map.
"""
from __future__ import annotations

import fnmatch
import json
import os
import re

from .ids import module_id, namespace_id
from .projects import MARKERS, Project, read_project

_MANIFEST = json.load(open(os.path.join(os.path.dirname(__file__), "..", "..", "codemap-plugin.json"), encoding="utf-8"))
_IGNORED = [re.compile(fnmatch.translate(p)) for p in _MANIFEST["detect"]["ignoreDirs"]]
_IGNORE_MARKERS = tuple(_MANIFEST["detect"]["ignoreMarkers"]) + ("conda-meta",)
# Build output and tools' folders: copies of the code, not the code (unless they are a package themselves).
_OUTPUT_DIRS = {"build", "dist", "node_modules", "wheelhouse", "_build", "site", "bin", "obj"}
_TEST_DIR = re.compile(r"(^|/)(tests?|testing)/")
_TEST_FILE = re.compile(r"(^|/)(test_[^/]*|[^/]*_tests?|tests|conftest)\.py$")
_GENERATED_NAME = re.compile(r"(_pb2|_pb2_grpc|_grpc)\.py$|(^|/)migrations/\d{4}_[^/]*\.py$")
_GENERATED_HEAD = re.compile(r"@generated|<auto-generated|auto-?generated|generated by|do not edit", re.I)


class ModuleInfo:
    """A .py file and where it sits: its project, its import names and its node."""

    def __init__(self, project: Project, file: str, path: str, analyzed: bool) -> None:
        self.project = project
        self.file = file
        self.path = path  # relative to the project, with /
        self.rel = ""  # relative to the analysis root, with /
        self.analyzed = analyzed
        self.is_package = os.path.basename(file) == "__init__.py"
        self.is_test = is_test_file(path)
        self.names: list[str] = []  # every dotted name it can be imported as, the main one first
        self.name = ""
        self.package = ""
        self.id = ""
        self.namespace_id = ""
        self.skipped = ""  # why it is not on the map though it is analyzed: "generated", "test", "empty"
        self.generated = False
        self.text: str | None = None
        self.tree = None
        self.parse_error = ""
        self.lines = 0
        self.symbols = None  # its symbol table, built when needed
        self.in_package = False  # its folder has __init__.py (relative imports work, the folder is not on sys.path)

    def __repr__(self) -> str:
        return f"<module {self.name} {self.path}>"


class Discovery:
    def __init__(self) -> None:
        self.projects: list[Project] = []
        self.modules: list[ModuleInfo] = []
        self.by_file: dict[str, ModuleInfo] = {}
        self.analyzed_projects: list[Project] = []


def is_test_file(path: str) -> bool:
    return bool(_TEST_DIR.search(path) or _TEST_FILE.search(path))


def is_generated(path: str, text: str) -> bool:
    if _GENERATED_NAME.search(path):
        return True
    head = "\n".join(text.splitlines()[:5])
    return bool(_GENERATED_HEAD.search(head))


def discover(target: str, root: str) -> Discovery:
    full = os.path.abspath(target)
    is_file = os.path.isfile(full)
    scan_dir = os.path.dirname(full) if is_file else full
    project_dirs: set[str] = set()
    files: list[str] = []

    above = None if _has_marker(scan_dir) else _marker_above(scan_dir)
    index_root = above or scan_dir
    _walk(index_root, files, project_dirs)
    if above:
        project_dirs.add(above)

    def owner(file: str) -> str:
        directory = os.path.dirname(file)
        while True:
            if directory in project_dirs:
                return directory
            parent = os.path.dirname(directory)
            if parent == directory or not _inside(directory, index_root):
                return scan_dir
            directory = parent

    def analyzed(file: str) -> bool:
        return file == full if is_file else _inside(file, scan_dir)

    discovery = Discovery()
    by_dir: dict[str, list[str]] = {}
    for file in files:
        by_dir.setdefault(owner(file), []).append(file)

    names: set[str] = set()
    for directory in sorted(by_dir):
        project = read_project(directory)
        base = project.declared_name or os.path.basename(directory) or "python"
        name = base
        i = 2
        while name in names:
            name = f"{base}~{i}"
            i += 1
        names.add(name)
        project.name = name
        discovery.projects.append(project)
        for file in sorted(by_dir[directory]):
            path = os.path.relpath(file, directory).replace(os.sep, "/")
            module = ModuleInfo(project, file, path, analyzed(file))
            module.rel = os.path.relpath(file, root).replace(os.sep, "/")
            project.modules.append(module)
            discovery.modules.append(module)
            discovery.by_file[file] = module

    _name_modules(discovery)
    discovery.analyzed_projects = [p for p in discovery.projects if any(m.analyzed for m in p.modules)]
    return discovery


def _name_modules(discovery: Discovery) -> None:
    """Dotted names: from the nearest folder above the module that is not a package (classic packages with
    __init__.py), and from every source root of its project that holds it (src/ layouts, namespace packages)."""
    init_cache: dict[str, bool] = {}

    def has_init(directory: str) -> bool:
        if directory not in init_cache:
            init_cache[directory] = os.path.isfile(os.path.join(directory, "__init__.py"))
        return init_cache[directory]

    for module in discovery.modules:
        directory = os.path.dirname(module.file)
        stem = os.path.splitext(os.path.basename(module.file))[0]
        module.in_package = has_init(directory)
        candidates: list[str] = []
        if module.in_package:
            # Up through the packages, as Python does, also past the project's or the analyzed folder's top.
            top = directory
            for _ in range(64):
                parent = os.path.dirname(top)
                if parent == top or not has_init(parent):
                    break
                top = parent
            candidates.append(_dotted(os.path.dirname(top), module.file))
        for source_root in module.project.roots:
            if _inside(module.file, source_root):
                candidates.append(_dotted(source_root, module.file))
        names = [n for n in dict.fromkeys(candidates) if n and _valid(n)] or [stem]
        module.names = names
        module.name = names[0]
        if module.is_package:
            module.package = module.name
        else:
            module.package = module.name.rpartition(".")[0]
        module.id = module_id(module.project.name, module.path)
        module.namespace_id = namespace_id(module.project.name, module.package)


def _dotted(source_root: str, file: str) -> str:
    rel = os.path.relpath(file, source_root).replace(os.sep, "/")
    if rel.startswith("../"):
        return ""
    parts = rel[:-3].split("/") if rel.endswith(".py") else rel.split("/")
    if parts[-1] == "__init__":
        parts = parts[:-1]
    return ".".join(parts)


def _valid(name: str) -> bool:
    return all(part.isidentifier() for part in name.split("."))


# ---------------------------------------------------------------------------------------------- walking


def skips_dir(path: str, name: str) -> bool:
    if name.startswith(".") or any(p.match(name) for p in _IGNORED):
        return True
    if any(os.path.exists(os.path.join(path, marker)) for marker in _IGNORE_MARKERS):
        return True  # a virtual environment or a conda environment, whatever its name
    return name in _OUTPUT_DIRS and not os.path.isfile(os.path.join(path, "__init__.py"))


def _walk(directory: str, files: list[str], project_dirs: set[str]) -> None:
    try:
        entries = sorted(os.scandir(directory), key=lambda e: e.name)
    except OSError:
        return
    for entry in entries:
        try:
            if entry.is_dir(follow_symlinks=False):
                if not skips_dir(entry.path, entry.name):
                    _walk(entry.path, files, project_dirs)
            elif entry.is_file():
                if entry.name in MARKERS:
                    project_dirs.add(directory)
                if entry.name.endswith(".py"):
                    files.append(entry.path)  # setup.py is code too
        except OSError:
            continue


def _has_marker(directory: str) -> bool:
    return any(os.path.isfile(os.path.join(directory, m)) for m in MARKERS)


def _marker_above(directory: str) -> str | None:
    """The project a folder is inside: the nearest folder above it with a project file, up to the repository's root."""
    home = os.path.expanduser("~")
    current = directory
    while True:
        parent = os.path.dirname(current)
        if parent == current or os.path.normcase(parent) == os.path.normcase(home):
            return None
        if _has_marker(parent):
            return parent
        if os.path.exists(os.path.join(parent, ".git")):
            return None
        current = parent


def _inside(path: str, directory: str) -> bool:
    return path == directory or path.startswith(directory.rstrip(os.sep) + os.sep)
